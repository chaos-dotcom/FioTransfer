//! `strings::*` and the C entry points that read their arguments with it.
//!
//! The contract under test, taken from the module's own documentation:
//!
//! * `from_c_str` is total: any `*const c_char` a shim can hand a `go*`
//!   callback (NULL, empty, 1 byte, 100 KB, invalid UTF-8, an interior NUL)
//!   yields a `String`, never a panic, and it keeps every valid byte prefix.
//! * `cstr` turns an interior NUL into a space and still yields a usable
//!   `CString`.
//! * `cstr_or_empty` turns an interior NUL into *nothing at all* — the whole
//!   string becomes empty (this is what the code does; the brief for this
//!   sweep assumed it becomes spaces, and it does not). Pinned here.
//!
//! The reference model for the first one is `common::lossy`, a hand-written
//! lossy UTF-8 decoder that shares no code with `CStr::to_string_lossy`.

mod common;

use std::ffi::{c_char, CString};
use std::sync::Mutex;

use fiotransfer_sys::strings::{cstr, cstr_or_empty, from_c_str};
use proptest::prelude::*;

use common::{arb_bytes, arb_string_with_nul, buffer_for_c};

/// One process-wide lock: the `go*` callbacks and their hooks are global
/// statics, so the tests that install hooks must not interleave.
static LOCK: Mutex<()> = Mutex::new(());

fn lock() -> std::sync::MutexGuard<'static, ()> {
    LOCK.lock().unwrap_or_else(|e| e.into_inner())
}

/// A NUL-terminated copy of `bytes`, read the way a shim's argument is read.
fn read_as_c(bytes: &[u8]) -> String {
    let buf = buffer_for_c(bytes);
    from_c_str(buf.as_ptr() as *const c_char)
}

proptest! {
    #![proptest_config(ProptestConfig { cases: 48, ..ProptestConfig::default() })]

    /// Totality, and the strongest statement about content: what comes back is
    /// exactly the lossy decoding of the bytes before the first NUL.
    #[test]
    fn from_c_str_is_the_lossy_prefix_of_its_buffer(bytes in arb_bytes()) {
        let got = read_as_c(&bytes);
        let want = common::lossy_c_prefix(&bytes);
        prop_assert_eq!(&got, &want, "bytes {:?}", &bytes[..bytes.len().min(64)]);
        // No expansion beyond one U+FFFD per ill-formed byte, and no loss of
        // valid text: the length is bounded by the bytes it read.
        prop_assert!(got.len() <= 3 * common::before_nul(&bytes).len());
    }

    /// The prefix property on its own terms: valid text first, then garbage.
    /// `from_c_str` must never lose a byte of the valid part.
    #[test]
    fn from_c_str_keeps_a_valid_prefix(prefix in any::<String>(), tail in proptest::collection::vec(1u8..=255u8, 0..24)) {
        let mut bytes = prefix.clone().into_bytes();
        bytes.extend_from_slice(&tail);
        let got = read_as_c(&bytes);
        prop_assert!(got.starts_with(&prefix), "lost prefix {:?} in {:?}", prefix, got);
        prop_assert_eq!(&got, &format!("{}{}", prefix, common::lossy(&tail)));
    }

    /// An interior NUL becomes a space, and the result is still a usable
    /// `CString` (no NUL inside, valid UTF-8).
    #[test]
    fn cstr_turns_every_interior_nul_into_a_space(s in prop_oneof![4 => arb_string_with_nul(), 1 => any::<String>()]) {
        prop_assume!(s.contains('\0'));
        let c = cstr(&s);
        let want = s.replace('\0', " ");
        prop_assert_eq!(c.to_str().expect("valid UTF-8"), want.as_str());
        prop_assert_eq!(c.as_bytes().len(), want.len());
    }

    /// Pinning `cstr_or_empty`: an interior NUL does not become a space, it
    /// makes the whole string empty. Whichever behaviour is intended, this is
    /// the one in the crate, and nothing panics either way.
    #[test]
    fn cstr_or_empty_yields_empty_when_there_is_an_interior_nul(s in prop_oneof![4 => arb_string_with_nul(), 1 => any::<String>()]) {
        let c = cstr_or_empty(&s);
        if s.contains('\0') {
            prop_assert_eq!(c.as_bytes(), b"", "s had a NUL: {:?}", s);
        } else {
            prop_assert_eq!(c.to_str().expect("valid UTF-8"), s.as_str());
        }
    }

    /// Where there is no NUL the two constructors agree with each other and
    /// with `CString::new`.
    #[test]
    fn the_two_constructors_agree_without_a_nul(s in arb_string_with_nul().prop_map(|s| s.replace('\0', "x"))) {
        let want = CString::new(s.as_bytes()).expect("no NUL");
        let (a, b) = (cstr(&s), cstr_or_empty(&s));
        prop_assert_eq!(a.as_bytes(), want.as_bytes());
        prop_assert_eq!(b.as_bytes(), want.as_bytes());
    }

    /// The real boundary: the `go*` entry points C links against, called with
    /// generated bytes the way `quick_darwin.m` / `services_darwin.m` /
    /// `tray_darwin.m` call them.
    #[test]
    fn go_callbacks_read_their_arguments_lossily(link in arb_bytes(), pass in arb_bytes(), dir in arb_bytes(), kind in any::<i32>()) {
        let _g = lock();
        let seen = std::sync::Arc::new(Mutex::new(Vec::<String>::new()));

        // The hooks are `fn` pointers, so the capture goes through statics.
        static QUICK_SEEN: Mutex<Option<std::sync::Arc<Mutex<Vec<String>>>>> = Mutex::new(None);
        static SERVICE_SEEN: Mutex<Option<std::sync::Arc<Mutex<Vec<String>>>>> = Mutex::new(None);
        static TRAY_SEEN: Mutex<Option<std::sync::Mutex<Vec<i32>>>> = Mutex::new(None);
        *QUICK_SEEN.lock().unwrap() = Some(seen.clone());

        fn quick_inspect(seq: i32, a: &str, b: &str) {
            if let Some(v) = QUICK_SEEN.lock().unwrap().as_ref() {
                let mut v = v.lock().unwrap();
                v.push(format!("inspect {seq}"));
                v.push(a.to_string());
                v.push(b.to_string());
            }
        }
        fn quick_dest(d: &str) {
            if let Some(v) = QUICK_SEEN.lock().unwrap().as_ref() {
                v.lock().unwrap().push(d.to_string());
            }
        }
        fiotransfer_sys::quick::set_quick_hooks(fiotransfer_sys::quick::QuickHooks {
            inspect: quick_inspect,
            dest: quick_dest,
            start: |a, b, c, on| {
                if let Some(v) = QUICK_SEEN.lock().unwrap().as_ref() {
                    let mut v = v.lock().unwrap();
                    v.push(format!("{a}|{b}|{c}|{on}"));
                }
            },
        });

        let cbuf = |b: &[u8]| {
            let mut v = b.to_vec();
            v.push(0);
            v
        };
        let (cl, cp, cd) = (cbuf(&link), cbuf(&pass), cbuf(&dir));
        fiotransfer_sys::quick::goQuickInspect(7, cl.as_ptr() as *const c_char, cp.as_ptr() as *const c_char);
        fiotransfer_sys::quick::goQuickStart(cl.as_ptr() as *const c_char, cp.as_ptr() as *const c_char, cd.as_ptr() as *const c_char, kind);
        fiotransfer_sys::quick::goQuickDest(cd.as_ptr() as *const c_char);

        let (l, p, d) = (common::lossy_c_prefix(&link), common::lossy_c_prefix(&pass), common::lossy_c_prefix(&dir));
        let got = seen.lock().unwrap().clone();
        let first = ["inspect 7".to_string(), l.clone()];
        prop_assert_eq!(&got[..2], &first[..]);
        prop_assert_eq!(got.get(2).map(String::as_str), Some(p.as_str()));
        let start_line = format!("{l}|{p}|{d}|{}", kind != 0);
        prop_assert_eq!(got.get(3).map(String::as_str), Some(start_line.as_str()));
        prop_assert_eq!(got.get(4).map(String::as_str), Some(d.as_str()));

        // The Finder service and the menu bar item, with kinds and tags.
        *SERVICE_SEEN.lock().unwrap() = Some(seen.clone());
        fn service(kind: i32, paths: &str) {
            if let Some(v) = SERVICE_SEEN.lock().unwrap().as_ref() {
                let mut v = v.lock().unwrap();
                v.push(format!("service {kind} {paths}"));
            }
        }
        fiotransfer_sys::services::set_service_hook(service);
        seen.lock().unwrap().clear();
        fiotransfer_sys::services::goService(kind, cl.as_ptr() as *const c_char);
        let want_service = vec![format!("service {kind} {l}")];
        let service_got = seen.lock().unwrap().clone();
        prop_assert_eq!(service_got, want_service);

        *TRAY_SEEN.lock().unwrap() = Some(Mutex::new(Vec::new()));
        fn tray(tag: i32) {
            if let Some(v) = TRAY_SEEN.lock().unwrap().as_ref() {
                v.lock().unwrap().push(tag);
            }
        }
        fiotransfer_sys::tray::set_tray_action(tray);
        fiotransfer_sys::tray::goTrayAction(kind);
        let tags: Vec<i32> = TRAY_SEEN.lock().unwrap().as_ref().unwrap().lock().unwrap().clone();
        prop_assert_eq!(tags, vec![kind]);
    }
}

#[test]
fn null_pointers_read_as_empty() {
    let _g = lock();
    assert_eq!(from_c_str(std::ptr::null()), "");
    let c = cstr("");
    assert_eq!(c.as_bytes(), b"");
    assert_eq!(cstr_or_empty("").as_bytes(), b"");
}

#[test]
fn the_nul_replacement_is_pinned_exactly() {
    let _g = lock();
    // One NUL in the middle, one at each end: three spaces, not a truncation.
    let s = "\0ab\0cd\0";
    assert_eq!(cstr(s).to_str().unwrap(), " ab cd ");
    // And the empty-string fallback: the whole string, not the prefix.
    assert_eq!(cstr_or_empty(s).as_bytes(), b"");
}
